export interface Env {
  ACCESS_TEAM_DOMAIN?: string;
  ACCESS_AUD?: string;
  ADMIN_EMAILS?: string;
  ADMIN_DEV_EMAIL?: string;
  TURNSTILE_SECRET_KEY?: string;
  RESEND_API_KEY?: string;
  FORM_FROM_EMAIL?: string;
  GOOGLE_SERVICE_ACCOUNT_EMAIL?: string;
  GOOGLE_PRIVATE_KEY?: string;
  FORM_SHEET_ID?: string;
  // Optional comma-separated addresses that get a blind copy of each nursery notification.
  FORM_BCC?: string;
  ASSETS: Fetcher;
  DB: D1Database;
  IMAGES: {
    input(stream: ReadableStream): {
      transform(options: Record<string, unknown>): {
        output(options: { format: string; quality: number }): Promise<{ response(): Response }>;
      };
    };
  };
}

export interface ExecutionContext {
  waitUntil(promise: Promise<unknown>): void;
  passThroughOnException(): void;
}

// Pages from the old Wix site that Google has indexed, sent to their new home
// with a permanent redirect so search rankings carry over.
const LEGACY_REDIRECTS: Record<string, string> = {
  "/abbeyroad/home-ar": "/abbey-road",
  "/abbeyroad/registration-form-ar": "/register?location=abbey-road",
  "/abbeyroad/abbey-road-open-day-registration-form": "/visit?location=abbey-road",
  "/activities": "/beckett-house",
  "/calendar": "/timetable",
  "/registration": "/register",
  "/registration-form": "/register?location=angel",
};

// Widths generated by scripts/responsive-images.mjs.
const RESPONSIVE_WIDTHS = [640, 1080];
const LONG_CACHE = "public, max-age=2592000, stale-while-revalidate=86400";

// Serves the pre-generated copy nearest to the requested srcset width, or the
// original when no smaller copy exists (small images, or widths above 1080px).
async function serveResponsiveImage(request: Request, url: URL, env: Env): Promise<Response> {
  const src = url.searchParams.get("url") ?? "";
  const width = Number(url.searchParams.get("w")) || 0;
  if (!/^\/images\/[\w\-/]+\.(webp|jpe?g|png|avif)$/i.test(src) || src.includes("..")) {
    return new Response("Bad image request", { status: 400 });
  }
  const target = RESPONSIVE_WIDTHS.find((candidate) => candidate >= width);
  const candidates = target ? [`/_responsive${src.replace(/\.[^.]+$/, "")}-${target}.webp`, src] : [src];
  for (const path of candidates) {
    const asset = await env.ASSETS.fetch(new Request(new URL(path, request.url)));
    if (!asset.ok) continue;
    const response = new Response(asset.body, asset);
    response.headers.set("Cache-Control", LONG_CACHE);
    return response;
  }
  return new Response("Not found", { status: 404 });
}

function adminPath(pathname: string) {
  let decoded = pathname;
  // Guard encoded aliases before vinext performs its own path normalisation.
  for (let i = 0; i < 10; i++) {
    try { const next = decodeURIComponent(decoded); if (next === decoded) break; decoded = next; } catch { break; }
  }
  const segments: string[] = [];
  for (const part of decoded.replace(/\\/g, "/").split("/")) {
    if (part === "..") segments.pop();
    else if (part && part !== ".") segments.push(part);
  }
  return "/" + segments.join("/").toLowerCase();
}

const worker = {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);

    // One canonical address: https and www.
    const toWww = url.hostname === "beckett-house.co.uk";
    if (toWww || (url.protocol === "http:" && url.hostname !== "localhost" && url.hostname !== "127.0.0.1")) {
      url.protocol = "https:";
      if (toWww) url.hostname = "www.beckett-house.co.uk";
      return Response.redirect(url.toString(), 301);
    }

    const legacy = LEGACY_REDIRECTS[url.pathname.toLowerCase().replace(/\/+$/, "")];
    if (legacy) return Response.redirect(new URL(legacy, url).toString(), 301);

    const protectedPath = adminPath(url.pathname);
    if (protectedPath === "/admin" || protectedPath.startsWith("/admin/") || protectedPath === "/api/admin" || protectedPath.startsWith("/api/admin/")) {
      const identity = await adminIdentity(request, env);
      if ("error" in identity) {
        if (protectedPath.startsWith("/api/")) return adminJson({ error: identity.error }, identity.status);
        return new Response(identity.error, { status: identity.status, headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store", "X-Robots-Tag": "noindex" } });
      }
      if (protectedPath.startsWith("/api/")) return handleAdmin(request, env, identity.email);
      const result = await handler.fetch(request, env, ctx);
      const response = new Response(result.body, result);
      response.headers.set("Cache-Control", "no-store");
      response.headers.set("X-Robots-Tag", "noindex");
      return response;
    }

    if (request.method === "POST" && (url.pathname === "/api/forms/visit" || url.pathname === "/api/forms/register")) {
      return handleForm(request, env, ctx, url.pathname === "/api/forms/visit" ? "visit" : "register");
    }

    if (url.pathname === "/_next/image" || url.pathname === "/_vinext/image") return serveResponsiveImage(request, url, env);

    return handler.fetch(request, env, ctx);
  },
};

export default worker;
